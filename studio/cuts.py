"""Assemble a self-contained HyperFrames project per cut: build/out/<project>-16x9 and -9x16.
The engine is inlined into the page (HyperFrames looks for the timeline registration in the page itself)."""
import json, shutil
from .common import ROOT, CUTS

HF_VERSION = json.loads((ROOT / "package.json").read_text(encoding="utf-8"))["hyperframesVersion"]


def _css_vars(p):
    pal, f = p.data["palette"], p.data.get("fonts", {})
    v = {"primary": pal["primary"], "primary2": pal.get("primary2", pal["primary"]), "secondary": pal.get("secondary", pal["primary"]),
         "accent": pal["accent"], "ink": pal["ink"], "ink2": pal.get("ink2", pal["ink"]), "paper": pal["paper"], "good": pal.get("good", "#16a34a"),
         "bad": pal.get("bad", "#e5484d"), "grad": pal.get("grad", f"linear-gradient(100deg,{pal['primary']},{pal['accent']})"),
         "f-title": f"'{f.get('title', 'DM Sans')}'", "f-body": f"'{f.get('body', 'Nunito')}'", "f-note": f"'{f.get('note', 'Caveat')}'"}
    return ";".join(f"--{k}:{val}" for k, val in v.items())


def slot_html(s, dd):
    """Media slot for a hook/broll beats scene s (id, type, start, end) with project data dd; "" for other types.
    data.media_in > 0 starts the clip that far into its source (data-media-start)."""
    if s["type"] not in ("hook", "broll"):
        return ""
    media, mi = dd.get("media") or "", float(dd.get("media_in") or 0)
    off = f' data-media-start="{mi:.3f}"' if mi > 0 else ""
    vid = (f'<video id="mv-{s["id"]}" class="clip" data-start="{s["start"]:.3f}" data-duration="{s["end"] - s["start"]:.3f}"{off} '
           f'muted playsinline src="assets/project/{media}"></video>') if media.lower().endswith(".mp4") else ""
    return f'<div class="mslot" id="slot-{s["id"]}"><div class="mzoom">{vid}</div></div>'


HUMOUR_AT = "/* ============================ BUILD ============================ */"


def uses_humour(data):
    """True when a scene uses the humour treatment: data.headline on a hook or data.clean on an end card."""
    return any((s.get("data") or {}).get("headline") or (s.get("data") or {}).get("clean") is True for s in data.get("scenes", []))


def uses_fieldnotes(data):
    """True when a scene is a field-notes explainer scene (type fieldnotes, engine/fieldnotes.js; experimental)."""
    return any(s.get("type") == "fieldnotes" for s in data.get("scenes", []))


def engine_js(data):
    """The engine inlined into the page: scenes.js, with engine/humour.js and engine/fieldnotes.js spliced in before the
    build section only for projects that use them, so every other project's page stays byte-identical."""
    js = (ROOT / "engine" / "scenes.js").read_text(encoding="utf-8")
    extra = [f for f, used in (("humour.js", uses_humour(data)), ("fieldnotes.js", uses_fieldnotes(data))) if used]
    if not extra:
        return js
    if js.count(HUMOUR_AT) != 1:
        raise SystemExit(f"engine/scenes.js: the build section marker is missing, so engine/{extra[0]} cannot be added")
    return js.replace(HUMOUR_AT, "".join((ROOT / "engine" / f).read_text(encoding="utf-8") for f in extra) + HUMOUR_AT)


def build(p, cut):
    w, h, tag = CUTS[cut]
    B = json.loads((p.build / f"beats-{cut}.json").read_text(encoding="utf-8"))
    d = p.out_dir(cut)
    if d.exists():
        shutil.rmtree(d / "assets", ignore_errors=True)
    (d / "assets" / "audio").mkdir(parents=True, exist_ok=True)
    # entertainment scenes (hook, broll) get a static media slot; an .mp4 is a timed <video> the renderer seeks,
    # like the transition clips, so it has to be in the page itself rather than created by the engine
    defs = {s["id"]: s for s in p.data["scenes"]}
    slot = lambda s: slot_html(s, defs[s["id"]].get("data") or {})
    scenes = "\n".join(f'  <section class="scene" id="{s["id"]}">{slot(s)}</section>' for s in B["scenes"])
    # transition clips (generated by `studio.py transitions`), laid over the scene boundary
    trans, starts = [], {s["id"]: s["start"] for s in B["scenes"]}
    for t in p.data.get("transitions", []):
        clip = p.gen / "transitions" / f"{t['id']}-{tag}.mp4"
        if not t.get("enabled", True) or t["scene"] not in starts or not clip.exists():
            continue
        dur = float(t.get("seconds", 1.2)); s0 = starts[t["scene"]]
        t0 = {"before": s0 - dur, "center": s0 - dur / 2}.get(t.get("align", "center"), s0)
        (d / "assets" / "transitions").mkdir(exist_ok=True)
        shutil.copy(clip, d / "assets" / "transitions" / clip.name)
        trans.append(f'  <video id="tr-{t["id"]}" class="transition clip" data-start="{max(0, t0):.3f}" data-duration="{dur:.3f}" data-track-index="{5 + len(trans)}" muted playsinline src="assets/transitions/{clip.name}"></video>')
    tpl = (ROOT / "engine" / "template.html").read_text(encoding="utf-8")
    html = (tpl.replace("{{TITLE}}", f"{p.data['name']} ({cut})").replace("{{CUT}}", cut).replace("{{W}}", str(w)).replace("{{H}}", str(h))
               .replace("{{WW}}", str(round(w * 1.7))).replace("{{DUR}}", str(B["duration"])).replace("{{SCENES}}", scenes)
               .replace("{{TRANSITIONS}}", "\n".join(trans)).replace("{{CSS_VARS}}", _css_vars(p))
               .replace("{{PROJECT_JSON}}", json.dumps({k: p.data.get(k) for k in ("name", "style", "layout", "brand", "palette", "backgrounds", "solids", "pose_aspect", "scenes")}))
               .replace("{{ENGINE}}", engine_js(p.data)))
    (d / "index.html").write_text(html, encoding="utf-8")
    (d / "package.json").write_text(json.dumps({"private": True, "hyperframesVersion": HF_VERSION}, indent=1), encoding="utf-8")
    shutil.copy(p.build / f"beats-{cut}.js", d / "beats.js")
    gsap = ROOT / "node_modules" / "gsap" / "dist" / "gsap.min.js"
    if not gsap.exists():
        raise SystemExit("node_modules/gsap is missing. Run `npm install` in the repo root.")
    shutil.copy(gsap, d / "assets" / "gsap.min.js")
    fonts = p.dir / "fonts" if (p.dir / "fonts" / "fonts.css").exists() else ROOT / "assets" / "fonts"
    shutil.copytree(fonts, d / "assets" / "fonts")
    for sub in ("brand", "poses", "images", "media"):
        if (p.dir / sub).exists():
            shutil.copytree(p.dir / sub, d / "assets" / "project" / sub, ignore=shutil.ignore_patterns("src", "*.psd"))
    shutil.copy(p.build / f"mix-{cut}.wav", d / "assets" / "audio" / "mix.wav")
    print(f"  page {cut}: {d}")
    return d
